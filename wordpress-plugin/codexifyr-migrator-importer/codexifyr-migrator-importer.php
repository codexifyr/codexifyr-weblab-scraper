function cxmi_handle_upload(){
    if (!current_user_can('manage_options') || empty($_POST['cxmi_nonce']) || !wp_verify_nonce($_POST['cxmi_nonce'],'cxmi_upload')) return;
    if (empty($_FILES['cxmi_zip']['tmp_name'])) {
        echo '<div class="notice notice-error"><p>No ZIP was uploaded.</p></div>'; return;
    }
    $name=sanitize_file_name($_FILES['cxmi_zip']['name']);
    if (strtolower(pathinfo($name,PATHINFO_EXTENSION))!=='zip'){
        echo '<div class="notice notice-error"><p>Please upload a .zip migration package.</p></div>'; return;
    }

    require_once ABSPATH.'wp-admin/includes/file.php';
    WP_Filesystem();
    $uploads=wp_upload_dir();
    $base=trailingslashit($uploads['basedir']).'codexifyr-migrator';
    wp_mkdir_p($base);
    $dir=$base.'/job-'.time().'-'.wp_generate_password(6,false,false);
    wp_mkdir_p($dir);
    $zip=$dir.'/migration.zip';
    if (!@move_uploaded_file($_FILES['cxmi_zip']['tmp_name'],$zip) && !@copy($_FILES['cxmi_zip']['tmp_name'],$zip)){
        echo '<div class="notice notice-error"><p>Could not save uploaded ZIP.</p></div>'; return;
    }
    $unz=unzip_file($zip,$dir.'/package');
    if (is_wp_error($unz)){
        echo '<div class="notice notice-error"><p>Could not extract migration ZIP: '.esc_html($unz->get_error_message()).'</p></div>'; return;
    }
    $data=cxmi_find_file($dir.'/package','site-data.json');
    if (!$data){
        echo '<div class="notice notice-error"><p>This is not a valid Codexifyr migration ZIP: site-data.json is missing.</p></div>'; return;
    }

    $theme=cxmi_find_file($dir.'/package','codexifyr-source-theme.zip');
    $theme_status='';
    if ($theme){
        $theme_status=cxmi_install_theme($theme);
    }

    $decoded=json_decode(file_get_contents($data),true);
    if (!is_array($decoded)){
        echo '<div class="notice notice-error"><p>site-data.json is invalid.</p></div>'; return;
    }

    update_option(CXMI_OPT,[
        'ready'=>true,'dir'=>$dir,'data'=>$data,'stage'=>'terms','index'=>0,
        'started'=>time(),'theme_status'=>$theme_status,'source_url'=>$decoded['source_url']??''
    ],false);
    echo '<div class="notice notice-success"><p>Migration ZIP loaded. '.esc_html($theme_status).' Click <strong>INSTALL WEBSITE</strong>.</p></div>';
}

function cxmi_find_file($root,$filename){
    if (!is_dir($root)) return '';
    $it=new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root,FilesystemIterator::SKIP_DOTS));
    foreach($it as $f) if($f->isFile() && $f->getFilename()===$filename) return $f->getPathname();
    return '';
}

function cxmi_install_theme($zip){
    require_once ABSPATH.'wp-admin/includes/class-wp-upgrader.php';
    require_once ABSPATH.'wp-admin/includes/theme.php';
    $skin=new Automatic_Upgrader_Skin();
    $up=new Theme_Upgrader($skin);
    $r=$up->install($zip,['overwrite_package'=>true]);
    if (is_wp_error($r)) return 'Theme install warning: '.$r->get_error_message();
    $themes=wp_get_themes();
    foreach($themes as $slug=>$theme){
        if (stripos($theme->get('Name'),'Codexifyr Source Store Theme')!==false){
            switch_theme($slug);
            return 'Generated Codexifyr theme installed and activated.';
        }
    }
    return 'Generated theme installed.';
}

